/**
 * Generates conformance vectors from path enumeration: for each path the checker finds through each
 * conformance flow that passes it, finds inputs that take that path, drives this engine along it,
 * checks that the engine ends the way the checker predicted, and records the run as a vector in
 * {@code conformance/generated/}. The test fails if the files there are not what it generates; run
 * it with {@code FAYE_REGENERATE=1} to rewrite them.
 */
class GeneratedVectorsTest {

    static final Path OUT = Fixtures.CONFORMANCE.resolve("generated");
    static final String SUBJECT = "alice";
    static final YAMLMapper YAML = YAMLMapper.builder()
            .disable(YAMLGenerator.Feature.WRITE_DOC_START_MARKER)
            .enable(YAMLGenerator.Feature.MINIMIZE_QUOTES)
            .enable(YAMLGenerator.Feature.ALWAYS_QUOTE_NUMBERS_AS_STRINGS)
            .enable(YAMLGenerator.Feature.INDENT_ARRAYS_WITH_INDICATOR)
            .build();
    static final int MAX_SOLUTIONS = 50;

    @Test
    void generatedVectorsAreCurrent() throws IOException {
        Map<String, String> generated = new TreeMap<>();
        List<String> unrealized = new ArrayList<>();
        try (Stream<Path> flows = Files.list(Fixtures.CONFORMANCE.resolve("flows"))) {
            for (Path file : flows.sorted().toList()) {
                String name = file.getFileName().toString().replace(".json", "");
                Flow flow = Fixtures.conformanceFlow(name);
                Report report = Checker.check(flow, Fixtures.handlers(), TenantPolicy.DEFAULT, Fixtures::hook);
                if (!report.ok()) continue;
                for (int i = 0; i < report.paths().size(); i++) {
                    FlowPath path = report.paths().get(i);
                    Optional<Map<String, Object>> vector = realize(name, flow, path);
                    if (vector.isEmpty()) {
                        if (path.succeeded()) unrealized.add(name + " " + path.describe());
                    } else {
                        generated.put(
                                name + "/" + String.format(Locale.ROOT, "%03d", i) + ".yaml",
                                "# Generated by faye-check GeneratedVectorsTest from path enumeration. Do not edit.\n"
                                        + YAML.writeValueAsString(vector.get()));
                    }
                }
            }
        }
        // Every success path of the shipped flows can be taken, so each has a vector. A failure path may
        // be one the checker cannot rule out but no input takes (no option enabled when the options'
        // conditions cover every case).
        assertThat(unrealized)
                .as("paths with no vector")
                .noneMatch(p -> p.startsWith("password-only ")
                        || p.startsWith("passkey-totp ")
                        || p.startsWith("partner-consent ")
                        || p.startsWith("risk-hook ")
                        || p.startsWith("hook-pick "));

        Map<String, String> existing = new TreeMap<>();
        try (Stream<Path> files = Files.walk(OUT)) {
            for (Path f : files.filter(Files::isRegularFile).toList()) {
                existing.put(OUT.relativize(f).toString().replace('\\', '/'), Files.readString(f));
            }
        }
        if ("1".equals(System.getenv("FAYE_REGENERATE"))) {
            for (String stale : existing.keySet()) {
                if (!generated.containsKey(stale)) Files.delete(OUT.resolve(stale));
            }
            for (var e : generated.entrySet()) {
                Files.createDirectories(OUT.resolve(e.getKey()).getParent());
                Files.writeString(OUT.resolve(e.getKey()), e.getValue());
            }
            return;
        }
        assertThat(existing)
                .as("conformance/generated is stale; run FAYE_REGENERATE=1 ./gradlew :faye-check:test")
                .isEqualTo(generated);
    }

    /** A vector that takes {@code path}, or empty if no inputs this generator tries take it. */
    static Optional<Map<String, Object>> realize(String name, Flow flow, FlowPath path) {
        Scenario.Solutions solutions = new Scenario.Solutions(path);
        for (int tries = 0; tries < MAX_SOLUTIONS; tries++) {
            Optional<Scenario> scenario = solutions.next();
            if (scenario.isEmpty()) return Optional.empty();
            try {
                return Optional.of(drive(name, flow, path, scenario.get()));
            } catch (Diverged e) {
                // The engine went another way with these inputs; try the next ones
            }
        }
        return Optional.empty();
    }

    // ---- driving the engine ----

    static final class Diverged extends RuntimeException {
        private static final long serialVersionUID = 1L;

        Diverged(String message) {
            super(message, null, false, false);
        }
    }

    /** Runs the engine along the path, answering screens, handler calls and hooks as the path says. */
    static Map<String, Object> drive(String name, Flow flow, FlowPath path, Scenario scenario) {
        HostKind kind = HostKind.valueOf(path.section().toUpperCase(Locale.ROOT));
        Map<String, Object> hydra = new LinkedHashMap<>(scenario.global("hydra"));
        if (kind == HostKind.CONSENT) hydra.put("subject", SUBJECT);
        Map<String, Object> client = scenario.global("client");

        var cursor = new Cursor(path.events());
        Map<String, List<Object>> scripts = new LinkedHashMap<>();
        List<Handler> handlers = new ArrayList<>();
        Fixtures.metadata()
                .forEach((handler, meta) -> handlers.add(new Handler() {
                    @Override
                    public String name() {
                        return handler;
                    }

                    @Override
                    public Set<String> amr() {
                        return Fixtures.amr(meta);
                    }

                    @Override
                    public boolean bindsSubject() {
                        return meta.path("binds_subject").asBoolean();
                    }

                    @Override
                    public Outcome invoke(Env env, Submission input, Map<String, Object> args) {
                        Called c = cursor.next(Called.class);
                        if (!c.handler().equals(handler)) throw new Diverged("called " + handler + ", path has " + c);
                        List<Object> script = scripts.computeIfAbsent(handler, h -> new ArrayList<>());
                        if (c.amr() == null) {
                            script.add(Map.of("fail", FlowPath.HANDLER_ERROR));
                            return Outcome.fail(FlowPath.HANDLER_ERROR);
                        }
                        Map<String, Object> user = scenario.patch(cursor.okCalls++ + 1);
                        boolean narrowed = !c.amr().isEmpty() && c.amr().size() < amr().size();
                        Map<String, Object> ok = new LinkedHashMap<>();
                        if (!user.isEmpty()) ok.put("user", user);
                        if (narrowed) ok.put("amr", c.amr());
                        script.add(ok.isEmpty() ? "ok" : Map.of("ok", ok));
                        return new Outcome.Ok(
                                user, bindsSubject() ? SUBJECT : null, narrowed ? Set.copyOf(c.amr()) : null);
                    }
                }));

        Map<String, List<Object>> hookScripts = new LinkedHashMap<>();
        HookRunner hooks = (tenantId, hook, ctx) -> {
            Hooked h = cursor.next(Hooked.class);
            if (!h.hook().equals(hook.id())) throw new Diverged("ran hook " + hook.id() + ", path has " + h);
            List<Object> script = hookScripts.computeIfAbsent(hook.id(), id -> new ArrayList<>());
            if (!h.ok()) {
                script.add(Map.of("throws", "scripted failure"));
                throw new HookException("scripted failure");
            }
            Map<String, Object> returns;
            if (h.pick() != null) {
                returns = Map.of("pick", h.pick());
            } else {
                Map<String, Object> set = scenario.varsPatch(++cursor.okHooks);
                returns = set.isEmpty() ? Map.of() : Map.of("set", set);
            }
            script.add(Map.of("returns", returns));
            return returns;
        };

        var versions = new InMemoryFlowVersions();
        versions.publish(Engine.DEFAULT_TENANT, FlowVersion.of(flow));
        var host = new MockFlowHost();
        host.register(new HostRequest(kind, "challenge-1", client, hydra));
        var engine =
                new Engine(versions, new HandlerRegistry(handlers), new InMemoryFlowStore(), host, Map.of(), hooks);

        List<Map<String, Object>> events = new ArrayList<>();
        EngineResponse response = engine.start(kind, "challenge-1", Map.of());
        while (response instanceof ScreenView view) {
            if (events.size() > 400) throw new Diverged("too many screens");
            Map<String, Object> expect = new LinkedHashMap<>();
            String type = String.valueOf(view.screen().get("type"));
            expect.put("expect_screen", type);
            if (view.step() != null) expect.put("expect_step", view.step());
            if (view.screen().get("options") != null) {
                expect.put("expect_options", view.screen().get("options"));
            }
            if (view.screen().get("errors") instanceof List<?> errors && !errors.isEmpty()) {
                expect.put("expect_error", ((Map<?, ?>) errors.get(0)).get("code"));
            }
            if (view.screen().get("attemptsLeft") != null) {
                expect.put("expect_attempts_left", view.screen().get("attemptsLeft"));
            }
            events.add(expect);
            Map<String, Object> answer = switch (type) {
                case "identifier" -> Map.of("identifier", "alice@example.com");
                case "password" -> Map.of("password", "correct horse battery staple");
                case "method_picker" ->
                    Map.of("method", cursor.next(Chose.class).option());
                case "passkey" -> Map.of("passkey", Map.of("id", "credential-1"));
                case "otp", "otp_enroll" -> Map.of("code", "123456");
                case "consent" -> Map.of("decision", "allow");
                case "error" -> Map.of();
                default -> throw new IllegalStateException("no answer for screen " + type);
            };
            events.add(Map.of("submit", answer));
            response = engine.submit(view.flowId(), view.nonce(), new Submission(answer));
        }
        assertThat(response).isInstanceOf(Redirect.class);
        cursor.finish();

        Map<String, Object> result = new LinkedHashMap<>();
        if (!host.rejected().isEmpty()) {
            result.put("succeed", false);
            result.put("reason", host.rejected().get(0).description());
        } else if (kind == HostKind.CONSENT) {
            result.put("succeed", true);
            result.put("subject", host.consented().get(0).outcome().subject());
            result.put("grant_scope", host.consented().get(0).outcome().grantScope());
        } else {
            var a = host.accepted().get(0).outcome();
            result.put("succeed", true);
            result.put("subject", a.subject());
            result.put("amr", a.amr());
            result.put("acr", a.acr());
        }
        assertThat(result)
                .as("engine result for " + name + " " + path.describe())
                .isEqualTo(predicted(path, hydra));
        events.add(Map.of("expect_result", result));

        Map<String, Object> vector = new LinkedHashMap<>();
        vector.put("name", name + ": " + path.describe());
        vector.put("ir", "flows/" + name + ".json");
        Map<String, Object> hostFields = new LinkedHashMap<>();
        if (kind == HostKind.CONSENT) hostFields.put("kind", "consent");
        if (!client.isEmpty()) hostFields.put("client", client);
        if (!hydra.isEmpty()) hostFields.put("hydra", hydra);
        if (!hostFields.isEmpty()) vector.put("host", hostFields);
        vector.put("handlers", scripts);
        if (!hookScripts.isEmpty()) vector.put("hooks", hookScripts);
        vector.put("events", events);
        return vector;
    }

    /** What the checker says the engine reports for this path. */
    static Map<String, Object> predicted(FlowPath path, Map<String, Object> hydra) {
        Map<String, Object> out = new LinkedHashMap<>();
        if (path.end() instanceof FlowPath.Failed f) {
            out.put("succeed", false);
            out.put("reason", f.reason());
        } else if (path.section().equals("consent")) {
            out.put("succeed", true);
            out.put("subject", SUBJECT);
            out.put("grant_scope", List.of());
        } else if (!Acr.satisfies(path.acr(), hydra.get("acr_values"))) {
            out.put("succeed", false);
            out.put("reason", "acr_not_satisfied");
        } else {
            out.put("succeed", true);
            out.put("subject", SUBJECT);
            out.put("amr", path.amr());
            out.put("acr", path.acr());
        }
        return out;
    }

    /** Walks the path's events as the engine asks for calls, hooks and picks. */
    static final class Cursor {
        final List<Event> events;
        int at;
        int okCalls;
        int okHooks;

        Cursor(List<Event> events) {
            this.events = events;
        }

        /** The next event of this type; no call or hook may be skipped to reach it. */
        <T extends Event> T next(Class<T> type) {
            while (at < events.size()) {
                Event e = events.get(at++);
                if (type.isInstance(e)) return type.cast(e);
                if (e instanceof Called || e instanceof Hooked) {
                    throw new Diverged("wanted " + type.getSimpleName() + ", path has " + e);
                }
            }
            throw new Diverged("path has no more " + type.getSimpleName());
        }

        void finish() {
            for (int i = at; i < events.size(); i++) {
                if (events.get(i) instanceof Called || events.get(i) instanceof Hooked) {
                    throw new Diverged("path has unused " + events.get(i));
                }
            }
        }
    }

    // ---- finding inputs ----

    /**
     * Inputs for one run: values for {@code hydra.*} and {@code client.*}, for {@code user.*} the
     * fields each succeeding call merges in, and for {@code vars.*} the values each hook in a step
     * sets. A variable is a path, plus for {@code user.*} the number of calls that succeeded before it
     * was read, and for {@code vars.*} the number of hooks in steps that did.
     */
    record Scenario(Map<Variable, Object> values) {

        static final Object ABSENT = new Object() {
            @Override
            public String toString() {
                return "absent";
            }
        };

        record Variable(String path, int version) {}

        Map<String, Object> global(String namespace) {
            Map<String, Object> out = new LinkedHashMap<>();
            values.forEach((v, value) -> {
                if (v.path().startsWith(namespace + ".") && value != ABSENT) {
                    put(out, v.path().substring(namespace.length() + 1), value);
                }
            });
            return out;
        }

        /** The {@code user.*} fields the {@code n}th succeeding call merges in. */
        Map<String, Object> patch(int n) {
            Map<String, Object> out = new LinkedHashMap<>();
            values.forEach((v, value) -> {
                if (v.path().startsWith("user.") && v.version() == n && value != ABSENT) {
                    put(out, v.path().substring("user.".length()), value);
                }
            });
            return out;
        }

        /** The {@code vars.*} the {@code n}th succeeding hook in a step sets. */
        Map<String, Object> varsPatch(int n) {
            Map<String, Object> out = new LinkedHashMap<>();
            values.forEach((v, value) -> {
                if (v.path().startsWith("vars.") && v.version() == n && value != ABSENT) {
                    out.put(v.path().substring("vars.".length()), value);
                }
            });
            return out;
        }

        /** {@code user.*} after {@code n} calls succeeded. */
        Map<String, Object> user(int n) {
            Map<String, Object> out = new HashMap<>();
            for (int i = 1; i <= n; i++) out.putAll(patch(i));
            return out;
        }

        @SuppressWarnings("unchecked")
        static void put(Map<String, Object> map, String dotted, Object value) {
            String[] parts = dotted.split("\\.");
            Map<String, Object> at = map;
            for (int i = 0; i < parts.length - 1; i++) {
                at = (Map<String, Object>) at.computeIfAbsent(parts[i], k -> new LinkedHashMap<String, Object>());
            }
            at.put(parts[parts.length - 1], value);
        }

        /** Assignments that satisfy every assumption on a path, found by backtracking. */
        static final class Solutions {
            final List<Constraint> constraints = new ArrayList<>();
            final List<Variable> variables = new ArrayList<>();
            final Map<Variable, List<Object>> candidates = new HashMap<>();
            final Map<Variable, Object> assigned = new HashMap<>();
            final List<Map<Variable, Object>> found = new ArrayList<>();
            boolean done;

            record Constraint(Assumed assumed, int version, int hooks, Set<Variable> reads) {}

            Solutions(FlowPath path) {
                int version = 0;
                int hooks = 0;
                for (Event e : path.events()) {
                    if (e instanceof Called c && c.ok()) version++;
                    if (e instanceof Hooked h && h.ok() && h.pick() == null) hooks++;
                    if (!(e instanceof Assumed a)) continue;
                    Set<Variable> reads = new LinkedHashSet<>();
                    collect(a.test(), version, hooks, reads);
                    constraints.add(new Constraint(a, version, hooks, reads));
                    for (Variable v : reads) {
                        if (!variables.contains(v)) variables.add(v);
                    }
                }
            }

            /** Variables a predicate reads, with the literals that could make each atom go either way. */
            void collect(Predicate p, int version, int hooks, Set<Variable> reads) {
                switch (p) {
                    case Predicate.And a -> a.all().forEach(q -> collect(q, version, hooks, reads));
                    case Predicate.Or o -> o.any().forEach(q -> collect(q, version, hooks, reads));
                    case Predicate.Not n -> collect(n.operand(), version, hooks, reads);
                    case Predicate.Path a -> variable(a.path(), version, hooks, reads, List.<Object>of(true, false));
                    case Predicate.Exists a -> variable(a.path(), version, hooks, reads, List.<Object>of("x"));
                    case Predicate.Compare c -> {
                        Object v = c.value();
                        List<Object> values = switch (c.op()) {
                            case EQ, NE ->
                                v instanceof Integer i
                                        ? List.<Object>of(i, i + 1)
                                        : v instanceof Boolean b
                                                ? List.<Object>of(b, !b)
                                                : List.<Object>of(v, v + "-other");
                            case GT, LT -> List.<Object>of(((Integer) v) + 1, ((Integer) v) - 1);
                            case HAS -> List.<Object>of(List.of(v), List.of());
                        };
                        variable(c.path(), version, hooks, reads, values);
                    }
                }
            }

            /** Only what a vector can set is a variable; anything else keeps the value the checker knew. */
            void variable(String path, int version, int hooks, Set<Variable> reads, List<Object> values) {
                String ns = path.substring(0, path.indexOf('.') < 0 ? path.length() : path.indexOf('.'));
                if (!"user".equals(ns) && !"hydra".equals(ns) && !"client".equals(ns) && !"vars".equals(ns)) return;
                // user.* before any call succeeded is empty; vars.* before any hook is what set wrote;
                // hydra.subject is fixed by the host kind
                if (("user".equals(ns) && version == 0)
                        || ("vars".equals(ns) && hooks == 0)
                        || "hydra.subject".equals(path)) {
                    return;
                }
                Variable v = new Variable(path, "user".equals(ns) ? version : "vars".equals(ns) ? hooks : -1);
                reads.add(v);
                List<Object> list = candidates.computeIfAbsent(v, k -> new ArrayList<>(List.of(ABSENT)));
                for (Object value : values) {
                    if (!list.contains(value)) list.add(value);
                }
            }

            Optional<Scenario> next() {
                if (found.isEmpty() && !done) {
                    search(0);
                    done = true;
                }
                return found.isEmpty() ? Optional.empty() : Optional.of(new Scenario(found.removeFirst()));
            }

            private void search(int i) {
                if (found.size() >= MAX_SOLUTIONS) return;
                if (i == variables.size()) {
                    found.add(new LinkedHashMap<>(assigned));
                    return;
                }
                Variable v = variables.get(i);
                for (Object value : candidates.getOrDefault(v, List.of())) {
                    assigned.put(v, value);
                    if (consistent()) search(i + 1);
                    assigned.remove(v);
                }
            }

            /** Every constraint whose variables are all assigned holds. */
            private boolean consistent() {
                Scenario partial = new Scenario(assigned);
                for (Constraint c : constraints) {
                    if (!assigned.keySet().containsAll(c.reads())) continue;
                    Env known = c.assumed().known();
                    Map<String, Object> vars = new HashMap<>(known.vars());
                    for (int i = 1; i <= c.hooks(); i++) vars.putAll(partial.varsPatch(i));
                    Env env = new Env(
                            Map.of(),
                            partial.global("client"),
                            known.tenant(),
                            partial.global("hydra"),
                            partial.user(c.version()),
                            vars,
                            known.auth());
                    if (Predicates.test(c.assumed().test(), env) != c.assumed().holds()) return false;
                }
                return true;
            }
        }
    }
}
